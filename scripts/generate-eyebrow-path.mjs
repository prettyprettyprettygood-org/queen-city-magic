// One-off generator, not part of the build: turns the fixed "you belong here" hero eyebrow
// copy into an SVG path traced from the actual "Nothing You Could Do" script font glyphs, so
// HandwritingReveal.astro can animate it with stroke-dasharray/dashoffset (a real pen-stroke
// draw, not a per-letter DOM fade). Re-run manually (`node scripts/generate-eyebrow-path.mjs`)
// only if the copy or font changes — the output is committed as static data, not regenerated
// on every build.
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";
import opentype from "opentype.js";
import wawoff2 from "wawoff2";

const TEXT = "You belong here";
const PADDING = 40;

const root = path.dirname(fileURLToPath(import.meta.url));
const fontPath = path.join(
  root,
  "../public/fonts/nothing-you-could-do-400.woff2",
);
const outPath = path.join(root, "../src/components/hero-eyebrow-path.ts");

const woff2Buffer = fs.readFileSync(fontPath);
const ttfBuffer = await wawoff2.decompress(woff2Buffer);
const font = opentype.parse(
  ttfBuffer.buffer.slice(
    ttfBuffer.byteOffset,
    ttfBuffer.byteOffset + ttfBuffer.byteLength,
  ),
);

const glyphPath = font.getPath(TEXT, 0, 0, font.unitsPerEm);
const d = glyphPath.toPathData(2);
const bbox = glyphPath.getBoundingBox();

const viewBox = [
  bbox.x1 - PADDING,
  bbox.y1 - PADDING,
  bbox.x2 - bbox.x1 + PADDING * 2,
  bbox.y2 - bbox.y1 + PADDING * 2,
].map((n) => Math.round(n * 100) / 100);

const contents = `// Generated by scripts/generate-eyebrow-path.mjs — do not hand-edit.
// Traces "${TEXT}" in the "Nothing You Could Do" font; re-run the script if either changes.
export const HERO_EYEBROW_TEXT = ${JSON.stringify(TEXT)};
export const HERO_EYEBROW_PATH_D = ${JSON.stringify(d)};
export const HERO_EYEBROW_VIEW_BOX = ${JSON.stringify(viewBox.join(" "))};
`;

fs.writeFileSync(outPath, contents);
console.log(
  `Wrote ${path.relative(process.cwd(), outPath)} — run \`npm run format\` afterward.`,
);
